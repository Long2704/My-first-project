import {readFileSync,readdirSync,writeFileSync} from 'node:fs';
import {resolve,relative,sep} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
export function buildPwa(directory='dist'){
 const root=resolve(directory),files=[];
 function walk(path){for(const entry of readdirSync(path,{withFileTypes:true})){const name=resolve(path,entry.name);if(entry.isDirectory())walk(name);else if(entry.isFile()){const rel=relative(root,name).split(sep).join('/');if(rel!=='sw.js')files.push(rel);}}}
 walk(root);files.sort();
 const hash=createHash('sha256');for(const file of files){hash.update(file);hash.update(readFileSync(resolve(root,file)));}
 const version=hash.digest('hex').slice(0,16),paths=files.map(file=>'/'+file);
 const source=`// Generated by scripts/build-pwa.mjs. Cache only this build's public static files.
const VERSION=${JSON.stringify(version)};
const PREFIX='goc-pho-shell-';
const CACHE=PREFIX+VERSION;
const FILES=${JSON.stringify(paths)};
const ALLOWED=new Set(FILES);
self.addEventListener('install',event=>{
 event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(FILES.map(path=>new Request(path,{cache:'reload'})))));
 // Wait for all old POS windows to close. Never force a working window to reload.
});
self.addEventListener('activate',event=>{
 event.waitUntil((async()=>{
  const keys=await caches.keys();await Promise.all(keys.filter(key=>key.startsWith(PREFIX)&&key!==CACHE).map(key=>caches.delete(key)));
  await self.clients.claim();
 })());
});
self.addEventListener('fetch',event=>{
 const request=event.request,url=new URL(request.url);
 if(request.method!=='GET'||url.origin!==self.location.origin||request.headers.has('authorization'))return;
 if(request.mode==='navigate'){
  event.respondWith((async()=>{
   const cache=await caches.open(CACHE),shell=await cache.match('/index.html');if(shell)return shell;
   try{return await fetch(request);}catch{return await cache.match('/offline.html')||Response.error();}
  })());return;
 }
 if(!ALLOWED.has(url.pathname))return;
 event.respondWith((async()=>{const cache=await caches.open(CACHE);return await cache.match(url.pathname)||fetch(request);})());
});
self.addEventListener('message',event=>{if(event.data?.type==='GET_VERSION')event.ports[0]?.postMessage({version:VERSION});});
`;
 writeFileSync(resolve(root,'sw.js'),source);return {version,files:paths};
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){const result=buildPwa(process.argv[2]??'dist');console.log(`PWA: ${result.files.length} static files, build ${result.version}`);}
